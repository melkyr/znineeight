#!/bin/sh
# tier_m3_sim.sh — UNDERSANDED M3 auto-sim/replay/sim-gate acceptance tier
# (spec §25.9, §34, §36 M3).
#
# FAST, native only (no Wine/DDraw evidence in this gate):
#   * build the native gate runner undtool.nix (-fsafe -W -osl +
#     build_target.sh linux) directly from undtool_native.zig
#   * run the M3 unit drivers (Tasks 1-4): replay_test, sim_test,
#     ruletest_test, safety_test, replay_cli_test (all -fsafe -W clean, PASS,
#     exit 0)
#   * run the M1 regression gate tier_m1_std.sh (Win9x exes/imports, native
#     paths driver, std fixtures, z9edit tier_edit + pinned lexer md5)
#   * run the M1/M2 regression gate tier_m2_fight.sh (core/behavior/fight/ui
#     drivers, full-fight goldens, purity, z9edit tier_edit + pinned lexer md5,
#     no .py tooling)
#   * sim gate on all 5 creatures: undtool.nix --sim 200 --creature <token>
#     --seed 98 --hull 150. Asserts
#       - header line exactly `defs actions=steps ascent=hull0 bars=switches prompt=modal`
#       - rare-fight avg actions <= 12 on each rare (Anemoniacus, Freezing Perch)
#       - ascent rate <= 15% (ascent_pm <= 150) at Hull 150
#       - bar-switch > 0
#       - commons never prompt (prompts == 0)
#       - fixed-seed determinism (same run twice -> byte-identical output)
#   * --test-rules exit 0 with rules_ok=100
#   * replay v2 golden byte-match: replay_test's final writer artifact is
#     byte-compared to tests/fixtures/replay_eel_98.rep (the fixture is
#     committed, never regenerated by the tier), and the native tool's
#     `--replay <fixture>` line is compared to its exact pinned output
#   * --dump-grid --screen fight output byte-compared to
#     tests/fixtures/dump_grid_fight.golden (committed golden, never regenerated)
#   * safety-net checks (decline costs no RNG, commons never prompt, surge
#     caps) are the safety_test driver cases, asserted PASS
#
# SLOW (Wine evidence, never the gate): if wine and a pre-built undtool.exe
# are both present, run a small sim as evidence; otherwise print an explicit
# operator-hardware skip line. An executed evidence failure makes the tier
# nonzero (never a silent skip).
#
# Env: ZIG  compiler (default /tmp/zig1-m1/zig1_5_clean)
#      OUT  scratch dir (default /tmp/undersanded_m3_tier)
#
# Run from anywhere (paths resolved from this script). Exits non-zero on any
# failure and prints `TIER_M3 PASS <n> passed / <m> failed`.

set -u

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
UNDDIR="$(cd "$SCRIPT_DIR/.." && pwd)"
ROOT="$(cd "$UNDDIR/../../.." && pwd)"
ZIG="${ZIG:-/tmp/zig1-m1/zig1_5_clean}"
OUT="${OUT:-/tmp/undersanded_m3_tier}"
TESTS="examples/z98/undersanded/tests"
FIXTURES="$SCRIPT_DIR/fixtures"
EXPECTED_LEXER_MD5="dcc81009e9a36c86e4d90e104c439871"
SIM_HEADER="defs actions=steps ascent=hull0 bars=switches prompt=modal"
REPLAY_ARTIFACT="/tmp/m3_t1_replay.rep"
REPLAY_LINE="replay outcome=1 actions=8 rng=1107243468 log=0:3:18:62;0:4:6:94;0:3:10:52;0:4:6:88;0:3:13:39;0:4:6:82;0:9:5:1;0:3:16:28;0:4:6:76;0:9:5:1;0:3:10:23;0:4:6:70;0:9:5:1;0:3:12:16;0:4:6:64;0:9:5:1;0:3:18:3;0:4:6:58;0:9:5:1;0:3:14:-6;0:5:0:0;"

PASSES=0
FAILS=0
SKIPS=0
pass_case() { echo "ok   - $1"; PASSES=$((PASSES + 1)); }
fail_case() { echo "FAIL - $1"; FAILS=$((FAILS + 1)); }
evidence_pass() { echo "EVIDENCE - $1"; PASSES=$((PASSES + 1)); }
evidence_fail() { echo "EVIDENCE-FAIL - $1"; FAILS=$((FAILS + 1)); }
skip_evidence() { echo "operator-hardware: EVIDENCE not run: $1"; SKIPS=$((SKIPS + 1)); }

if [ ! -x "$ZIG" ]; then
    echo "FAIL: compiler not found: $ZIG"
    echo "      build it: bash scripts/seed/build_from_seed.sh release/seed/zig1-seed.tgz /tmp/zig1-m1"
    exit 1
fi
if [ ! -f "$FIXTURES/replay_eel_98.rep" ] || [ ! -f "$FIXTURES/dump_grid_fight.golden" ]; then
    echo "FAIL: M3 fixture missing under $FIXTURES"
    exit 1
fi

rm -rf "$OUT"
mkdir -p "$OUT"
cd "$ROOT" || exit 1

# Extract an unsigned decimal field from one sim report line.
sim_field() {
    printf '%s\n' "$1" | sed -n "s/.* $2=\([0-9][0-9]*\).*/\1/p"
}

# ---------------------------------------------------------------------------
# FAST 1: native gate runner undtool.nix (-fsafe -W clean)
# ---------------------------------------------------------------------------
echo "== FAST: native undtool.nix =="
NATIVE="$OUT/native"
mkdir -p "$NATIVE"
NIX_OK=0
if "$ZIG" -fsafe -W -osl --output-dir "$NATIVE" \
    examples/z98/undersanded/undtool_native.zig >"$OUT/undtool_compile.log" 2>&1; then
    pass_case "undtool_native.zig -fsafe -W compile clean"
    if sh "$NATIVE/build_target.sh" linux "$NATIVE/undtool.nix" \
        >"$OUT/undtool_link.log" 2>&1; then
        pass_case "undtool.nix built natively (build_target.sh linux)"
        NIX_OK=1
    else
        fail_case "undtool.nix native link failed (see $OUT/undtool_link.log)"
        tail -20 "$OUT/undtool_link.log" | sed 's/^/       /'
    fi
else
    fail_case "undtool_native.zig compile failed (see $OUT/undtool_compile.log)"
    tail -20 "$OUT/undtool_compile.log" | sed 's/^/       /'
fi
NIX="$NATIVE/undtool.nix"

# ---------------------------------------------------------------------------
# FAST 2: M3 unit drivers (Tasks 1-4), -fsafe -W clean, PASS, exit 0
# ---------------------------------------------------------------------------
echo "== FAST: M3 unit drivers (replay/sim/ruletest/safety) =="
run_driver() {
    t="$1"
    td="$OUT/$t"
    mkdir -p "$td"
    if ! "$ZIG" -fsafe -W -osl --output-dir "$td" "$TESTS/$t.zig" \
        >"$td/zig.log" 2>&1; then
        fail_case "$t -fsafe -W compile failed (see $td/zig.log)"
        tail -20 "$td/zig.log" | sed 's/^/       /'
        return
    fi
    pass_case "$t -fsafe -W compile clean"
    if ! sh "$td/build_target.sh" linux "$td/$t" >"$td/build.log" 2>&1; then
        fail_case "$t native link failed (see $td/build.log)"
        tail -20 "$td/build.log" | sed 's/^/       /'
        return
    fi
    pass_case "$t built natively (build_target.sh linux)"
    timeout 180 "$td/$t" >"$td/run.log" 2>&1
    rc=$?
    sed 's/^/       /' "$td/run.log"
    if [ "$rc" -eq 0 ] && grep -qx "$t PASS" "$td/run.log" \
        && ! grep -q '^FAIL - ' "$td/run.log"; then
        cases="$(grep -c '^ok - ' "$td/run.log")"
        pass_case "$t PASS (exit 0; $cases cases)"
    else
        fail_case "$t did not pass (rc=$rc; see $td/run.log)"
    fi
}

rm -f "$REPLAY_ARTIFACT"
for t in replay_test sim_test ruletest_test safety_test replay_cli_test; do
    run_driver "$t"
done

# Safety-net cases are part of the spec §34 M3 row; assert them by name too.
SAFETY_LOG="$OUT/safety_test/run.log"
if [ -f "$SAFETY_LOG" ]; then
    for c in decline_no_rng f_esc_decline_no_rng common_never_prompts \
        surge_caps_via_failures; do
        if grep -qx "ok - $c" "$SAFETY_LOG"; then
            pass_case "safety_test: $c"
        else
            fail_case "safety_test: $c missing/failed"
        fi
    done
else
    fail_case "safety_test run log missing (driver build failed)"
fi

# ---------------------------------------------------------------------------
# FAST 3: replay v2 golden byte-match (committed fixture, not regenerated)
# ---------------------------------------------------------------------------
echo "== FAST: replay v2 golden byte-match =="
if [ -f "$REPLAY_ARTIFACT" ]; then
    if cmp -s "$REPLAY_ARTIFACT" "$FIXTURES/replay_eel_98.rep"; then
        pass_case "replay v2 writer output byte-identical to replay_eel_98.rep"
    else
        fail_case "replay v2 writer output differs from replay_eel_98.rep"
        diff -u "$FIXTURES/replay_eel_98.rep" "$REPLAY_ARTIFACT" 2>/dev/null | sed 's/^/       /'
    fi
else
    fail_case "replay v2 writer artifact missing ($REPLAY_ARTIFACT)"
fi

# Native `--replay <fixture>` must print the exact pinned report line.
if [ "$NIX_OK" -eq 1 ]; then
    if timeout 120 "$NIX" --replay "$FIXTURES/replay_eel_98.rep" \
        >"$OUT/replay_cli.log" 2>&1; then
        printf '%s\n' "$REPLAY_LINE" >"$OUT/replay_cli.expected"
        if cmp -s "$OUT/replay_cli.log" "$OUT/replay_cli.expected"; then
            pass_case "undtool.nix --replay fixture prints exact pinned line"
        else
            fail_case "undtool.nix --replay line differs from pinned output"
            diff -u "$OUT/replay_cli.expected" "$OUT/replay_cli.log" 2>/dev/null | sed 's/^/       /'
        fi
    else
        fail_case "undtool.nix --replay fixture failed (see $OUT/replay_cli.log)"
    fi
else
    fail_case "--replay skipped (undtool.nix did not build)"
fi

# ---------------------------------------------------------------------------
# FAST 4: M1 regression gate (Win9x exes/imports, paths, std fixtures, z9edit)
# ---------------------------------------------------------------------------
echo "== FAST: M1 regression (tier_m1_std.sh) =="
M1LOG="$OUT/tier_m1_std.log"
if ZIG="$ZIG" OUT="$OUT/m1" sh "$TESTS/tier_m1_std.sh" >"$M1LOG" 2>&1; then
    pass_case "tier_m1_std.sh green (M1 std/exes/paths + tier_edit)"
else
    fail_case "tier_m1_std.sh failed (see $M1LOG)"
fi
tail -8 "$M1LOG" | sed 's/^/       /'
if grep -q '^TIER_M1 PASS' "$M1LOG"; then
    pass_case "tier_m1_std summary PASS"
else
    fail_case "tier_m1_std summary missing/FAIL"
fi

# ---------------------------------------------------------------------------
# FAST 5: M1/M2 regression gate (drivers, goldens, z9edit, no .py)
# ---------------------------------------------------------------------------
echo "== FAST: M1/M2 regression (tier_m2_fight.sh) =="
M2LOG="$OUT/tier_m2_fight.log"
if ZIG="$ZIG" OUT="$OUT/m2" sh "$TESTS/tier_m2_fight.sh" >"$M2LOG" 2>&1; then
    pass_case "tier_m2_fight.sh green (core/behavior/fight/ui + goldens)"
else
    fail_case "tier_m2_fight.sh failed (see $M2LOG)"
fi
tail -8 "$M2LOG" | sed 's/^/       /'
if grep -q '^TIER_M2 PASS ' "$M2LOG"; then
    pass_case "tier_m2_fight summary PASS"
else
    fail_case "tier_m2_fight summary missing/FAIL"
fi
for t in core_test behavior_test fight_test ui_test; do
    if grep -qE "(^|[[:space:]])$t PASS$" "$M2LOG"; then
        pass_case "tier_m2_fight: $t PASS"
    else
        fail_case "tier_m2_fight: $t PASS missing"
    fi
done

LEX_LINE="$(grep 'lexer md5 3x:' "$M2LOG" | tail -1)"
if [ -n "$LEX_LINE" ]; then
    MD1="$(printf '%s\n' "$LEX_LINE" | awk '{print $4}')"
    MD2="$(printf '%s\n' "$LEX_LINE" | awk '{print $5}')"
    MD3="$(printf '%s\n' "$LEX_LINE" | awk '{print $6}')"
    if [ -n "$MD1" ] && [ "$MD1" = "$MD2" ] && [ "$MD2" = "$MD3" ]; then
        pass_case "z9edit lexer goldens byte-identical 3x ($MD1)"
    else
        fail_case "z9edit lexer goldens differ ($MD1 / $MD2 / $MD3)"
    fi
    if [ "$MD1" = "$EXPECTED_LEXER_MD5" ]; then
        pass_case "z9edit lexer md5 unchanged ($MD1)"
    else
        fail_case "z9edit lexer md5 changed (got $MD1, want $EXPECTED_LEXER_MD5)"
    fi
else
    fail_case "z9edit lexer md5 line missing from tier_m2 output"
fi

PY_FILES="$(git -C "$ROOT" ls-files examples/z98/undersanded | grep '\.py$' || true)"
if [ -z "$PY_FILES" ]; then
    pass_case "no committed .py tooling under examples/z98/undersanded/"
else
    fail_case "committed .py tooling found under examples/z98/undersanded/"
    printf '%s\n' "$PY_FILES" | sed 's/^/       /'
fi

# ---------------------------------------------------------------------------
# FAST 6: --test-rules exit 0 with rules_ok=100
# ---------------------------------------------------------------------------
echo "== FAST: --test-rules =="
if [ "$NIX_OK" -eq 1 ]; then
    timeout 120 "$NIX" --test-rules >"$OUT/test_rules.log" 2>&1
    RC=$?
    sed 's/^/       /' "$OUT/test_rules.log"
    if [ "$RC" -eq 0 ] && grep -qx 'rules_ok=100' "$OUT/test_rules.log"; then
        pass_case "--test-rules exit 0 with rules_ok=100"
    else
        fail_case "--test-rules failed (rc=$RC; want exit 0 + rules_ok=100)"
    fi
else
    fail_case "--test-rules skipped (undtool.nix did not build)"
fi

# ---------------------------------------------------------------------------
# FAST 7: --dump-grid golden byte-match (committed fixture)
# ---------------------------------------------------------------------------
echo "== FAST: --dump-grid golden byte-match =="
if [ "$NIX_OK" -eq 1 ]; then
    if timeout 120 "$NIX" --dump-grid "$OUT/grid_fight.txt" --screen fight \
        >"$OUT/dump_grid.log" 2>&1; then
        if cmp -s "$OUT/grid_fight.txt" "$FIXTURES/dump_grid_fight.golden"; then
            pass_case "--dump-grid --screen fight byte-identical to dump_grid_fight.golden"
        else
            fail_case "--dump-grid --screen fight differs from golden"
            diff -u "$FIXTURES/dump_grid_fight.golden" "$OUT/grid_fight.txt" 2>/dev/null | sed 's/^/       /'
        fi
    else
        fail_case "--dump-grid --screen fight failed (see $OUT/dump_grid.log)"
    fi
else
    fail_case "--dump-grid skipped (undtool.nix did not build)"
fi

# ---------------------------------------------------------------------------
# FAST 8: sim gate — 5 creatures at --hull 150, seed 98, 200 fights
# ---------------------------------------------------------------------------
echo "== FAST: sim gate (200 fights, seed 98, hull 150) =="
TABLE="$OUT/sim_table.txt"
printf 'token actions rare_actions ascent_pm switches_pct prompts\n' >"$TABLE"
SIM_OK=1
for tok in eel electric_eel steel_tuna anemoniacus freezing_perch; do
    LOG="$OUT/sim_$tok.log"
    LOG2="$OUT/sim_${tok}_rerun.log"
    if [ "$NIX_OK" -ne 1 ]; then
        fail_case "sim $tok skipped (undtool.nix did not build)"
        SIM_OK=0
        continue
    fi
    timeout 180 "$NIX" --sim 200 --creature "$tok" --seed 98 --hull 150 \
        >"$LOG" 2>&1
    RC=$?
    if [ "$RC" -ne 0 ]; then
        fail_case "sim $tok exited $RC (see $LOG)"
        SIM_OK=0
        continue
    fi

    HEADER="$(sed -n '1p' "$LOG")"
    if [ "$HEADER" = "$SIM_HEADER" ]; then
        pass_case "sim $tok header exact"
    else
        fail_case "sim $tok header mismatch: $HEADER"
    fi

    REPORT="$(sed -n '2p' "$LOG")"
    case "$REPORT" in
        "sim creature=$tok fights=200 "*) : ;;
        *) fail_case "sim $tok report line malformed: $REPORT"; SIM_OK=0; continue ;;
    esac
    ACTIONS="$(sim_field "$REPORT" actions_avg)"
    RARE="$(sim_field "$REPORT" rare_actions_avg)"
    ASCENT="$(sim_field "$REPORT" ascent_pm)"
    SWITCH="$(sim_field "$REPORT" bar_switch_pct)"
    PROMPTS="$(sim_field "$REPORT" prompts)"
    if [ -z "$ACTIONS" ] || [ -z "$RARE" ] || [ -z "$ASCENT" ] \
        || [ -z "$SWITCH" ] || [ -z "$PROMPTS" ]; then
        fail_case "sim $tok report fields missing: $REPORT"
        SIM_OK=0
        continue
    fi
    printf '%s %s %s %s %s %s\n' \
        "$tok" "$ACTIONS" "$RARE" "$ASCENT" "$SWITCH" "$PROMPTS" >>"$TABLE"

    # Fixed-seed determinism: same command twice -> identical stdout.
    timeout 180 "$NIX" --sim 200 --creature "$tok" --seed 98 --hull 150 \
        >"$LOG2" 2>&1
    if cmp -s "$LOG" "$LOG2"; then
        pass_case "sim $tok deterministic (same seed -> identical output)"
    else
        fail_case "sim $tok non-deterministic across identical runs"
    fi

    # Ascent rate gate: <= 15% at Hull 150 (ascent_pm <= 150).
    if [ "$ASCENT" -le 150 ]; then
        pass_case "sim $tok ascent ${ASCENT}pm <= 150pm (15%) at hull 150"
    else
        fail_case "sim $tok ascent ${ASCENT}pm > 150pm (15%) at hull 150"
    fi

    # Bar-switch observed (fights with >=1 switch > 0).
    if [ "$SWITCH" -gt 0 ]; then
        pass_case "sim $tok bar-switch ${SWITCH}% > 0"
    else
        fail_case "sim $tok no bar-switch observed"
    fi

    case "$tok" in
        anemoniacus|freezing_perch)
            # Rare-fight avg actions gate: <= 12.
            if [ "$RARE" -le 12 ]; then
                pass_case "sim $tok rare actions ${RARE} <= 12"
            else
                fail_case "sim $tok rare actions ${RARE} > 12"
            fi
            ;;
        *)
            # Commons never prompt (spec §34).
            if [ "$PROMPTS" -eq 0 ]; then
                pass_case "sim $tok commons prompts=0"
            else
                fail_case "sim $tok commons prompts=${PROMPTS} (want 0)"
            fi
            ;;
    esac
done

echo "   measured sim gate table (hull 150, seed 98, 200 fights):"
sed 's/^/       /' "$TABLE"

# ---------------------------------------------------------------------------
# SLOW: Wine evidence only (never the gate); never a silent skip.
# ---------------------------------------------------------------------------
echo "== SLOW: Wine evidence (never the gate) =="
UNDTOOL_EXE="$UNDDIR/out/undtool.exe"
if command -v wine >/dev/null 2>&1 && [ -f "$UNDTOOL_EXE" ]; then
    WLOG="$OUT/wine_sim.log"
    if timeout 180 wine "$UNDTOOL_EXE" --sim 5 --creature eel --seed 98 --hull 150 \
        >"$WLOG" 2>&1 </dev/null; then
        if grep -qx "$SIM_HEADER" "$WLOG"; then
            evidence_pass "wine undtool.exe --sim 5 eel seed 98 (output line matches)"
        else
            evidence_fail "wine undtool.exe --sim ran but header line missing/mismatched"
        fi
    else
        evidence_fail "wine undtool.exe --sim failed (see $WLOG)"
    fi
else
    skip_evidence "wine or $UNDTOOL_EXE absent (native tier is the gate)"
fi

echo
echo "== tier_m3_sim summary: $PASSES passed, $FAILS failed, $SKIPS evidence skips =="
if [ "$FAILS" -ne 0 ]; then
    echo "TIER_M3 FAIL $PASSES passed / $FAILS failed"
    exit 1
fi
echo "TIER_M3 PASS $PASSES passed / $FAILS failed"
exit 0
