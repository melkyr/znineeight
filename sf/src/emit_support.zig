// emit_support.zig — hand-written support-file emitter for the C89 backend.
//
// Holds the canonical bytes of the compiler's runtime/platform support files as
// Z98 string constants and writes them into the user's output directory, so the
// emitted tree is self-contained (`-I .` + compiling every emitted `.c`).
// Canonical single source of truth on disk:
//   sf/src/include/zig_compat.h, zig_runtime.h, net_prelude.h,
//   zig_runtime.c, zig_pal.c, and sf/src/c_exit.c
// scripts/check_emit_support.sh asserts emitted == canonical byte-for-byte.
//
// This module is the "std-kind helper" the compiler imports; the bytes live in
// the compiler source (NO host-side generator, NO perl, NO generated module).

const c89_mod = @import("c89_emit.zig");
const BufferedWriter = c89_mod.BufferedWriter;

pub fn emitZigCompatHSupport(writer: *BufferedWriter) void {
    c89_mod.bufferedWriterWrite(writer, "/* zig_compat.h - C89 compatibility layer */\n");
    c89_mod.bufferedWriterWrite(writer, "#ifndef ZIG_COMPAT_H\n");
    c89_mod.bufferedWriterWrite(writer, "#define ZIG_COMPAT_H\n");
    c89_mod.bufferedWriterWrite(writer, "\n");
    c89_mod.bufferedWriterWrite(writer, "#ifdef _MSC_VER\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef __int64 z64;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef unsigned __int64 zu64;\n");
    c89_mod.bufferedWriterWrite(writer, "#elif defined(__WATCOMC__)\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef long long z64;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef unsigned long long zu64;\n");
    c89_mod.bufferedWriterWrite(writer, "#else\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef long long z64;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef unsigned long long zu64;\n");
    c89_mod.bufferedWriterWrite(writer, "#endif\n");
    c89_mod.bufferedWriterWrite(writer, "\n");
    c89_mod.bufferedWriterWrite(writer, "#if !defined(__cplusplus) && !defined(__WATCOMC__)\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef signed char i8;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef short i16;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef int i32;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef z64 i64;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef unsigned char u8;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef unsigned short u16;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef unsigned int u32;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef zu64 u64;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef float f32;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef double f64;\n");
    c89_mod.bufferedWriterWrite(writer, "    typedef unsigned int usize;\n");
    c89_mod.bufferedWriterWrite(writer, "#endif\n");
    c89_mod.bufferedWriterWrite(writer, "\n");
    c89_mod.bufferedWriterWrite(writer, "typedef int bool;\n");
    c89_mod.bufferedWriterWrite(writer, "#define true 1\n");
    c89_mod.bufferedWriterWrite(writer, "#define false 0\n");
    c89_mod.bufferedWriterWrite(writer, "\n");
    c89_mod.bufferedWriterWrite(writer, "#ifndef NULL\n");
    c89_mod.bufferedWriterWrite(writer, "#define NULL ((void*)0)\n");
    c89_mod.bufferedWriterWrite(writer, "#endif\n");
    c89_mod.bufferedWriterWrite(writer, "\n");
    c89_mod.bufferedWriterWrite(writer, "#endif /* ZIG_COMPAT_H */\n");
}

pub fn emitNetPreludeHSupport(writer: *BufferedWriter) void {
    c89_mod.bufferedWriterWrite(writer, "/* net_prelude.h — target-neutral net include prelude for std_net extern calls\n");
    c89_mod.bufferedWriterWrite(writer, "   (S2 std_net extern rewrite). The include set mirrors the legacy socket-builtin\n");
    c89_mod.bufferedWriterWrite(writer, "   net include block (c89_emit.zig emitBuiltinIncludes); whichever C toolchain\n");
    c89_mod.bufferedWriterWrite(writer, "   compiles the dump (gcc -m32 / i686-w64-mingw32-gcc) selects the branch, so the\n");
    c89_mod.bufferedWriterWrite(writer, "   only prototype source for every std_net extern is the matching OS header. */\n");
    c89_mod.bufferedWriterWrite(writer, "#ifdef _WIN32\n");
    c89_mod.bufferedWriterWrite(writer, "#define WIN32_LEAN_AND_MEAN\n");
    c89_mod.bufferedWriterWrite(writer, "#include <windows.h>\n");
    c89_mod.bufferedWriterWrite(writer, "#include <winsock.h>\n");
    c89_mod.bufferedWriterWrite(writer, "#pragma comment(lib, \"wsock32.lib\")\n");
    c89_mod.bufferedWriterWrite(writer, "#else\n");
    c89_mod.bufferedWriterWrite(writer, "#include <sys/socket.h>\n");
    c89_mod.bufferedWriterWrite(writer, "#include <netinet/in.h>\n");
    c89_mod.bufferedWriterWrite(writer, "#include <arpa/inet.h>\n");
    c89_mod.bufferedWriterWrite(writer, "#include <sys/select.h>\n");
    c89_mod.bufferedWriterWrite(writer, "#include <sys/time.h>\n");
    c89_mod.bufferedWriterWrite(writer, "#include <unistd.h>\n");
    c89_mod.bufferedWriterWrite(writer, "#include <netdb.h>\n");
    c89_mod.bufferedWriterWrite(writer, "#endif\n");
    c89_mod.bufferedWriterWrite(writer, "\n");
    c89_mod.bufferedWriterWrite(writer, "/* std_net extern-call aliases. std_net's public API owns the names\n");
    c89_mod.bufferedWriterWrite(writer, "   accept/connect/send/recv/close/select, so those externs are declared with an\n");
    c89_mod.bufferedWriterWrite(writer, "   _os Z98 identifier and mapped here to the real OS symbols. Declared AFTER the\n");
    c89_mod.bufferedWriterWrite(writer, "   includes so they never rewrite the OS headers; only the emitted std_net call\n");
    c89_mod.bufferedWriterWrite(writer, "   sites (compiled into the same TU) are affected. */\n");
    c89_mod.bufferedWriterWrite(writer, "#define accept_os accept\n");
    c89_mod.bufferedWriterWrite(writer, "#define connect_os connect\n");
    c89_mod.bufferedWriterWrite(writer, "#define send_os send\n");
    c89_mod.bufferedWriterWrite(writer, "#define recv_os recv\n");
    c89_mod.bufferedWriterWrite(writer, "#define close_os close\n");
    c89_mod.bufferedWriterWrite(writer, "#define select_os select\n");
}

pub fn emitCExitCSupport(writer: *BufferedWriter) void {
    c89_mod.bufferedWriterWrite(writer, "#include <stdlib.h>\n");
    c89_mod.bufferedWriterWrite(writer, "void c_exit(int code) { exit(code); }\n");
}

pub fn emitZigRuntimeHSupport(writer: *BufferedWriter, safe_checks: bool) void {
    c89_mod.bufferedWriterWrite(writer, "#ifndef ZIG_RUNTIME_H\n");
    c89_mod.bufferedWriterWrite(writer, "#define ZIG_RUNTIME_H\n");
    c89_mod.bufferedWriterWrite(writer, "\n");
    c89_mod.bufferedWriterWrite(writer, "#include \"zig_compat.h\"\n");
    c89_mod.bufferedWriterWrite(writer, "\n");
    c89_mod.bufferedWriterWrite(writer, "extern void pal_print_stderr(const char* s, unsigned int len);\n");
    c89_mod.bufferedWriterWrite(writer, "extern void pal_abort(void);\n");
    c89_mod.bufferedWriterWrite(writer, "extern void pal_trap(void);\n");
    c89_mod.bufferedWriterWrite(writer, "extern int pal_i64_to_str(long long val, char* buf, int bufsize);\n");
    c89_mod.bufferedWriterWrite(writer, "extern int pal_u64_to_str(unsigned long long val, char* buf, int bufsize);\n");
    c89_mod.bufferedWriterWrite(writer, "extern int pal_f64_to_str(double val, char* buf, int bufsize);\n");
    if (safe_checks) {
        c89_mod.bufferedWriterWrite(writer, "\n");
        c89_mod.bufferedWriterWrite(writer, "/* -fsafe undefined poison: byte-exact 0xAA fill (emitted only under -fsafe). */\n");
        c89_mod.bufferedWriterWrite(writer, "void zig_poison_fill(void* p, unsigned int n);\n");
        c89_mod.bufferedWriterWrite(writer, "\n");
        c89_mod.bufferedWriterWrite(writer, "/* -fsafe integer-overflow helpers (A15). The UB-free wrap/flag math lives\n");
        c89_mod.bufferedWriterWrite(writer, "   here (header-static, like the __bootstrap_* cast helpers) so every\n");
        c89_mod.bufferedWriterWrite(writer, "   emitted module is self-sufficient; the C89 emitter only maps the LIR\n");
        c89_mod.bufferedWriterWrite(writer, "   *_with_overflow / overflow_flag ops to these calls. Emitted under -fsafe\n");
        c89_mod.bufferedWriterWrite(writer, "   only, so -ffast output is byte-unchanged. */\n");
        c89_mod.bufferedWriterWrite(writer, "static long long zig_ovf_sext(unsigned long long x, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    unsigned long long m;\n");
        c89_mod.bufferedWriterWrite(writer, "    if (w == 0u) return 0;\n");
        c89_mod.bufferedWriterWrite(writer, "    if (w >= 64u) return (long long)x;\n");
        c89_mod.bufferedWriterWrite(writer, "    m = (1ULL << w) - 1ULL;\n");
        c89_mod.bufferedWriterWrite(writer, "    x = x & m;\n");
        c89_mod.bufferedWriterWrite(writer, "    if ((x & (1ULL << (w - 1u))) != 0ULL) x = x | (~m);\n");
        c89_mod.bufferedWriterWrite(writer, "    return (long long)x;\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static unsigned long long zig_ovf_mask(unsigned long long x, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    if (w == 0u) return 0;\n");
        c89_mod.bufferedWriterWrite(writer, "    if (w >= 64u) return x;\n");
        c89_mod.bufferedWriterWrite(writer, "    return x & ((1ULL << w) - 1ULL);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static unsigned long long zig_ovf_maxu(unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    if (w >= 64u) return ~0ULL;\n");
        c89_mod.bufferedWriterWrite(writer, "    return (1ULL << w) - 1ULL;\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static long long zig_ovf_maxs(unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    if (w >= 64u) return 9223372036854775807LL;\n");
        c89_mod.bufferedWriterWrite(writer, "    return (long long)((1ULL << (w - 1u)) - 1ULL);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static long long zig_ovf_mins(unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    if (w >= 64u) return -9223372036854775807LL - 1LL;\n");
        c89_mod.bufferedWriterWrite(writer, "    return -(long long)(1ULL << (w - 1u));\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static long long zig_wrap_add_s(long long a, long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return zig_ovf_sext((unsigned long long)a + (unsigned long long)b, w);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static long long zig_wrap_sub_s(long long a, long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return zig_ovf_sext((unsigned long long)a - (unsigned long long)b, w);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static long long zig_wrap_mul_s(long long a, long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return zig_ovf_sext((unsigned long long)a * (unsigned long long)b, w);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static long long zig_wrap_shl_s(long long a, long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return zig_ovf_sext(((unsigned long long)a) << (((unsigned long long)b) & 63ULL), w);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static long long zig_wrap_neg_s(long long a, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return zig_ovf_sext((unsigned long long)0 - (unsigned long long)a, w);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static unsigned long long zig_wrap_add_u(unsigned long long a, unsigned long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return zig_ovf_mask(a + b, w);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static unsigned long long zig_wrap_sub_u(unsigned long long a, unsigned long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return zig_ovf_mask(a - b, w);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static unsigned long long zig_wrap_mul_u(unsigned long long a, unsigned long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return zig_ovf_mask(a * b, w);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static unsigned long long zig_wrap_shl_u(unsigned long long a, unsigned long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return zig_ovf_mask(a << (b & 63ULL), w);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static unsigned long long zig_wrap_neg_u(unsigned long long a, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return zig_ovf_mask((unsigned long long)0 - a, w);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static int zig_overflow_flag_add_s(long long a, long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    long long maxs = zig_ovf_maxs(w);\n");
        c89_mod.bufferedWriterWrite(writer, "    long long mins = zig_ovf_mins(w);\n");
        c89_mod.bufferedWriterWrite(writer, "    if (b > 0 && a > maxs - b) return 1;\n");
        c89_mod.bufferedWriterWrite(writer, "    if (b < 0 && a < mins - b) return 1;\n");
        c89_mod.bufferedWriterWrite(writer, "    return 0;\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static int zig_overflow_flag_add_u(unsigned long long a, unsigned long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return a > zig_ovf_maxu(w) - b;\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static int zig_overflow_flag_sub_s(long long a, long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    long long maxs = zig_ovf_maxs(w);\n");
        c89_mod.bufferedWriterWrite(writer, "    long long mins = zig_ovf_mins(w);\n");
        c89_mod.bufferedWriterWrite(writer, "    if (b < 0 && a > maxs + b) return 1;\n");
        c89_mod.bufferedWriterWrite(writer, "    if (b > 0 && a < mins + b) return 1;\n");
        c89_mod.bufferedWriterWrite(writer, "    return 0;\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static int zig_overflow_flag_sub_u(unsigned long long a, unsigned long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    (void)w;\n");
        c89_mod.bufferedWriterWrite(writer, "    return a < b;\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static int zig_overflow_flag_mul_s(long long a, long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    long long maxs = zig_ovf_maxs(w);\n");
        c89_mod.bufferedWriterWrite(writer, "    long long mins = zig_ovf_mins(w);\n");
        c89_mod.bufferedWriterWrite(writer, "    if (a == 0 || b == 0) return 0;\n");
        c89_mod.bufferedWriterWrite(writer, "    if (a > 0) {\n");
        c89_mod.bufferedWriterWrite(writer, "        if (b > 0) return a > maxs / b;\n");
        c89_mod.bufferedWriterWrite(writer, "        return b < mins / a;\n");
        c89_mod.bufferedWriterWrite(writer, "    }\n");
        c89_mod.bufferedWriterWrite(writer, "    if (b > 0) return a < mins / b;\n");
        c89_mod.bufferedWriterWrite(writer, "    return a < maxs / b;\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static int zig_overflow_flag_mul_u(unsigned long long a, unsigned long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    if (b == 0ULL) return 0;\n");
        c89_mod.bufferedWriterWrite(writer, "    return a > zig_ovf_maxu(w) / b;\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static int zig_overflow_flag_shl_s(long long a, long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    long long maxs = zig_ovf_maxs(w);\n");
        c89_mod.bufferedWriterWrite(writer, "    long long mins = zig_ovf_mins(w);\n");
        c89_mod.bufferedWriterWrite(writer, "    if (a == 0 || b <= 0) return 0;\n");
        c89_mod.bufferedWriterWrite(writer, "    if (b >= (long long)w) return 1;\n");
        c89_mod.bufferedWriterWrite(writer, "    return a > (maxs >> b) || a < (mins >> b);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static int zig_overflow_flag_shl_u(unsigned long long a, unsigned long long b, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    if (a == 0ULL || b == 0ULL) return 0;\n");
        c89_mod.bufferedWriterWrite(writer, "    if (b >= (unsigned long long)w) return 1;\n");
        c89_mod.bufferedWriterWrite(writer, "    return a > (zig_ovf_maxu(w) >> b);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static int zig_overflow_flag_neg_s(long long a, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    return a == zig_ovf_mins(w);\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
        c89_mod.bufferedWriterWrite(writer, "static int zig_overflow_flag_neg_u(unsigned long long a, unsigned int w) {\n");
        c89_mod.bufferedWriterWrite(writer, "    (void)w;\n");
        c89_mod.bufferedWriterWrite(writer, "    return a != 0ULL;\n");
        c89_mod.bufferedWriterWrite(writer, "}\n");
    }
    c89_mod.bufferedWriterWrite(writer, "\n");
    c89_mod.bufferedWriterWrite(writer, "/* Backward compat aliases __bootstrap_print* / __bootstrap_write /\n");
    c89_mod.bufferedWriterWrite(writer, "   __bootstrap_sleep_ms / __bootstrap_panic REMOVED (F4, 2026-08-08) — the\n");
