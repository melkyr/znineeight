    c89_mod.bufferedWriterWrite(writer, "\n");
    c89_mod.bufferedWriterWrite(writer, "/* Arena */\n");
    c89_mod.bufferedWriterWrite(writer, "void* arena_alloc_default(unsigned int size);\n");
