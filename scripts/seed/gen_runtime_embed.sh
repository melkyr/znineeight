#!/usr/bin/env bash
set -euo pipefail
# gen_runtime_embed.sh - authoring-time generator for sf/src/runtime_embed.zig.
#
# Embeds the canonical bytes of the runtime/platform support files as Z98
# string constants (Task 4 / spec 5.3, Task-1 decision 1). The emitted output
# dir must be self-contained; the compiler carries these bytes in its own
# binary rather than reading the source tree at run time.
#
# NOT invoked by build_from_seed.sh. Rerun when sf/src/include/* or
# sf/src/c_exit.c change, then verify with scripts/seed/check_runtime_embed.sh
# and commit the regenerated sf/src/runtime_embed.zig.
#
# usage: scripts/seed/gen_runtime_embed.sh [out_file]

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="${1:-$ROOT/sf/src/runtime_embed.zig}"

emit() {
    local ident="$1" file="$2"
    printf 'pub const %s: []const u8 = "' "$ident"
    perl -0777 -pe 's/\\/\\\\/g; s/"/\\"/g; s/\n/\\n/g' "$file"
    printf '";\n'
}

{
    printf '// AUTO-GENERATED by scripts/seed/gen_runtime_embed.sh -- DO NOT EDIT.\n'
    printf '// Canonical bytes of the runtime/platform support files written into a\n'
    printf '// user output dir (Task 4, spec 5.3). Regenerate when sf/src/include/*\n'
    printf '// or sf/src/c_exit.c change; gate: scripts/seed/check_runtime_embed.sh.\n\n'
    emit zig_compat_h  "$ROOT/sf/src/include/zig_compat.h"
    emit zig_runtime_h "$ROOT/sf/src/include/zig_runtime.h"
    emit net_prelude_h "$ROOT/sf/src/include/net_prelude.h"
    emit zig_runtime_c "$ROOT/sf/src/include/zig_runtime.c"
    emit zig_pal_c     "$ROOT/sf/src/include/zig_pal.c"
    emit c_exit_c      "$ROOT/sf/src/c_exit.c"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "[embed] wrote $OUT ($(wc -c < "$OUT") bytes)"
