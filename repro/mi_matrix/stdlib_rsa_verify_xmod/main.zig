// stdlib_rsa_verify_xmod — STDLIB std_crypto (L5) RSA verify GREEN fixture.
//
// std_crypto.zig is a PURE (no imports, no allocation) Z98 module; this
// fixture imports it by module basename and exercises the verify-only RSA
// API:
//   - rsaVerifyPkcs1v15(n, e, HashAlg, hash, sig)  (RFC 8017 §8.2.2)
//   - rsaVerifyPss(n, e, HashAlg, hash, salt_len, sig) (RFC 8017 §8.1.2)
//
// Key/vectors: 2048-bit RSA key generated independently with OpenSSL
// (`openssl genrsa`); signatures produced with `openssl dgst`:
//   - PKCS#1 v1.5 over a fixed message, SHA-256 and SHA-384 (2 good)
//   - PSS/SHA-256 sugar with salt_len 32 and 0 (2 good)
// Corrupted signatures flip one byte of a valid signature; every negative
// case MUST return error.BadSignature, never silently accept.
//
// GREEN (contract): deterministic byte-exact stdout `crypto rsa verify ok\n`
// (RUNRC=0). A mismatch increments g_fail and calls @panic.
const std = @import("std");
const crypto = @import("std_crypto.zig");

var g_fail: u32 = 0;

fn ck(cond: bool, what: []const u8) void {
    if (!cond) {
        g_fail += 1;
        @panic(what);
    }
}

fn checkGoodPkcs1(n: []const u8, e: u32, alg: crypto.HashAlg, hash: []const u8, sig: []const u8, what: []const u8) void {
    var ok: bool = true;
    crypto.rsaVerifyPkcs1v15(n, e, alg, hash, sig) catch |err| {
        ck(err == error.BadSignature, what);
        ok = false;
    };
    ck(ok, what);
}

fn checkBadPkcs1(n: []const u8, e: u32, alg: crypto.HashAlg, hash: []const u8, sig: []const u8, what: []const u8) void {
    var saw: bool = false;
    crypto.rsaVerifyPkcs1v15(n, e, alg, hash, sig) catch |err| {
        ck(err == error.BadSignature, what);
        saw = true;
    };
    ck(saw, what);
}

fn checkGoodPss(n: []const u8, e: u32, alg: crypto.HashAlg, hash: []const u8, salt_len: u32, sig: []const u8, what: []const u8) void {
    var ok: bool = true;
    crypto.rsaVerifyPss(n, e, alg, hash, salt_len, sig) catch |err| {
        ck(err == error.BadSignature, what);
        ok = false;
    };
    ck(ok, what);
}

fn checkBadPss(n: []const u8, e: u32, alg: crypto.HashAlg, hash: []const u8, salt_len: u32, sig: []const u8, what: []const u8) void {
    var saw: bool = false;
    crypto.rsaVerifyPss(n, e, alg, hash, salt_len, sig) catch |err| {
        ck(err == error.BadSignature, what);
        saw = true;
    };
    ck(saw, what);
}

