const std = @import("std");
const crypto = @import("std_crypto.zig");

var g_fail: u32 = 0;

fn ck(cond: bool, what: []const u8) void {
    if (!cond) {
        g_fail += 1;
        @panic(what);
    }
}

fn ckBytes(got: []const u8, want: []const u8, what: []const u8) void {
    ck(got.len == want.len, what);
    var i: usize = 0;
    while (i < got.len) : (i += 1) {
        ck(got[i] == want[i], what);
    }
}

fn check384(msg: []const u8, want: *const [48]u8, what: []const u8) void {
    var s = crypto.sha384Init();
    crypto.sha384Update(&s, msg);
    var d: [48]u8 = undefined;
    crypto.sha384Final(&s, &d);
    ckBytes(d[0..], want[0..], what);
}

fn check512(msg: []const u8, want: *const [64]u8, what: []const u8) void {
    var s = crypto.sha512Init();
    crypto.sha512Update(&s, msg);
    var d: [64]u8 = undefined;
    crypto.sha512Final(&s, &d);
    ckBytes(d[0..], want[0..], what);
}

