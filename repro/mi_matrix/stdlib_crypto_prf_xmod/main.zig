// (RUNRC=0). A mismatch increments g_fail and calls @panic.
const std = @import("std");
const crypto = @import("std_crypto.zig");

var g_fail: u32 = 0;

fn ck(cond: bool, what: []const u8) void {
    if (!cond) {
        g_fail += 1;
        @panic(what);
    }
}

fn ckBytes(got: []const u8, want: []const u8, what: []const u8) void {
    ck(got.len == want.len, what);
    var i: usize = 0;
    while (i < got.len) : (i += 1) {
        ck(got[i] == want[i], what);
    }
}

fn checkHmac(key: []const u8, msg: []const u8, want: *const [32]u8, what: []const u8) void {
    var d: [32]u8 = undefined;
    crypto.hmacSha256(key, msg, &d);
    ckBytes(d[0..], want[0..], what);

    var s = crypto.hmacSha256Init(key);
    crypto.hmacSha256Update(&s, msg);
    var d2: [32]u8 = undefined;
    crypto.hmacSha256Final(&s, &d2);
    ckBytes(d2[0..], want[0..], what);
}

fn checkExpand(prk: *const [32]u8, info: []const u8, out: []u8, want: []const u8, what: []const u8) void {
    var ok: bool = true;
    crypto.hkdfExpand(prk, info, out) catch |e| {
        ok = false;
        ck(e == error.Corrupt, what);
    };
    ck(ok, what);
    ckBytes(out, want, what);
}

fn checkBlake2s(key: []const u8, msg: []const u8, out_len: u32, want: []const u8, what: []const u8) void {
    var out: [32]u8 = undefined;
    var s = crypto.blake2sInit(key, out_len);
    crypto.blake2sUpdate(&s, msg);
    crypto.blake2sFinal(&s, out[0..@intCast(usize, out_len)]);
    ckBytes(out[0..@intCast(usize, out_len)], want, what);
}

